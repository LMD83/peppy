/**
 * Extra Irish/UK supermarket staples — the second half of the food bank.
 *
 * Same contract as foods.ts: per-100 g as bought, effort as a first-class
 * input, EU-14 allergens as a planning aid. Energy is the Atwater sum so the
 * catalogue check stays honest. The pack in your hand is still the authority.
 */

import type { Allergen, FoodDef, FoodEffort, FoodEquipment, FoodGroup, FoodShelf, FoodTag } from "./foods";

function atwater(proteinG: number, carbsG: number, fatG: number): number {
  return Math.round(4 * proteinG + 4 * carbsG + 9 * fatG);
}

function food(def: {
  key: string;
  name: string;
  group: FoodGroup;
  proteinG: number;
  carbsG: number;
  fatG: number;
  fiberG?: number;
  sodiumMg?: number;
  portionG: number;
  portionLabel: string;
  handPortion: string;
  effort: FoodEffort;
  equipment: FoodEquipment;
  shelf: FoodShelf;
  tags?: FoodTag[];
  allergens?: Allergen[];
  hands?: 1 | 2;
  standingMinutes?: number;
}): FoodDef {
  const standing =
    def.standingMinutes ??
    (def.effort === "none" ? 0 : def.effort === "assemble" ? 1 : def.effort === "heat" ? 2 : 8);
  return {
    key: def.key,
    name: def.name,
    group: def.group,
    per100: {
      kcal: atwater(def.proteinG, def.carbsG, def.fatG),
      proteinG: def.proteinG,
      carbsG: def.carbsG,
      fatG: def.fatG,
      fiberG: def.fiberG ?? 0,
      sodiumMg: def.sodiumMg ?? 0,
    },
    portionG: def.portionG,
    portionLabel: def.portionLabel,
    tags: def.tags ?? [],
    effort: def.effort,
    equipment: def.equipment,
    hands: def.hands ?? (def.effort === "cook" ? 2 : 1),
    standingMinutes: standing,
    shelf: def.shelf,
    handPortion: def.handPortion,
    allergens: def.allergens ?? [],
  };
}

