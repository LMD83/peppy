export type FoodDef = {
  key: string;
  name: string;
  group: FoodGroup;
  per100: {
    kcal: number;
    proteinG: number;
    carbsG: number;
    fatG: number;
    fiberG: number;
    sodiumMg: number;
  };
  /** The portion the picker offers first — a normal serving, not a target. */
  portionG: number;
  portionLabel: string;
  tags: FoodTag[];
  effort: FoodEffort;
  equipment: FoodEquipment;
  /** 1 means it can be done one-handed. 2 means it cannot. */
  hands: 1 | 2;
  /**
   * Minutes on your feet at the counter or the hob for one portion — the
   * hands-on cost, not the wall clock. An oven tray is five minutes of standing
   * and forty of waiting; the forty are not yours to spend.
   */
  standingMinutes: number;
  shelf: FoodShelf;
  /** Portion without scales: "1 palm", "1 cupped hand", "1 fist". */
  handPortion: string;
  /** EU 14, as they apply to the typical product. The pack always wins. */
  allergens: Allergen[];
};

