const BY_KEY: Map<string, FoodDef> = new Map(FOODS.map((f) => [f.key, f]));

/** Catalogue lookup. Returns undefined for a key that is not in the file. */
export function foodByKey(key: string): FoodDef | undefined {
  return BY_KEY.get(key);
}

/** True when the kitchen you have today can reach this food. */
export function reachableWith(food: FoodDef, available: FoodEquipment): boolean {
  return EQUIPMENT_RANK[food.equipment] <= EQUIPMENT_RANK[available];
}

/** The more capable of two kitchens — used to cap a preset by what you own. */
export function lesserEquipment(a: FoodEquipment, b: FoodEquipment): FoodEquipment {
  return EQUIPMENT_RANK[a] <= EQUIPMENT_RANK[b] ? a : b;
}
