/**
 * Static food catalogue — staples available in any Irish/UK supermarket.
 *
 * Values are per 100 g of the food as it is bought and weighed (raw for meat,
 * dry for grains, drained for tins), taken from standard composition tables.
 * They are reference values, not measurements of your shopping: treat them as
 * a good estimate, never as an analysis of the food in your kitchen.
 *
 * Every food also carries what it *costs to make*: effort, the equipment it
 * needs, whether it can be done one-handed, and the minutes it puts you on your
 * feet. On a bad day that is the binding constraint, not the macros, so the
 * planner reads these fields as first-class inputs rather than as decoration.
 *
 * Tinned, frozen and ready-made are first-class here. Frozen vegetables match
 * or beat fresh on most nutrients, and a cupboard survives a week nobody
 * planned for — the catalogue says so instead of treating fresh as the only
 * real food.
 *
 * Allergens are the EU's 14 named allergens (Regulation 1169/2011, Annex II) as
 * they apply to the *typical* product on a shelf. They are a planning aid, not
 * a label: the pack in your hand is the authority, always.
 *
 * Static config, not user data — no row here belongs to anybody.
 */

export type FoodGroup =
  | "protein"
  | "carb"
  | "veg"
  | "fruit"
  | "dairy"
  | "fat"
  | "convenience";

export type FoodTag = "high-protein" | "low-sodium" | "quick" | "bulk";

/**
 * What making it actually asks of you.
 * none — eat it as it comes. assemble — open, pour, drain, spread; no heat.
 * heat — a microwave or a kettle. cook — a hob or an oven.
 */
export type FoodEffort = "none" | "assemble" | "heat" | "cook";

/**
 * The least capable appliance that will do. Ranked (see EQUIPMENT_RANK): a
 * kitchen that has an oven also has a microwave, so a food is reachable when
 * its requirement ranks at or below what you have today.
 */
export type FoodEquipment = "none" | "kettle" | "microwave" | "one-pan" | "oven";

/** Where it lives — and therefore whether it survives an unplanned week. */
export type FoodShelf = "fresh" | "fridge" | "freezer" | "cupboard";

